/* ==========================================================================
   DocBrisk Standalone Dashboard Export
   Produces one self-contained .html file: the KPI values and chart data
   are baked in as plain JSON (no live connection back to the workbook),
   and Chart.js is pulled from a CDN the same way DocBrisk's own PDF tools
   load their libraries on demand. Opens directly in any browser, and can
   be uploaded anywhere as a static file.
   ========================================================================== */

const DashboardExport = (() => {

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  }

  function formatDisplay(kpi) {
    if (kpi.format === 'currency') return '₹' + KpiEngine.formatNumber(kpi.value);
    if (kpi.format === 'percent') return KpiEngine.formatNumber(kpi.value) + '%';
    return KpiEngine.formatNumber(kpi.value);
  }

  /**
   * @param {string} title          dashboard title shown at the top
   * @param {Array}  filledSlots    output of KpiTemplates.autoFill()
   * @returns {string} a complete HTML document as a string
   */
  function buildHtml(title, filledSlots) {
    const scorecards = filledSlots.filter((s) => s.kpi && s.kpi.chart === 'scorecard');
    const charts = filledSlots.filter((s) => s.kpi && s.kpi.chart !== 'scorecard');

    const chartData = charts.map((slot, i) => ({
      id: 'chart' + i,
      title: slot.kpi.label,
      type: slot.kpi.chart === 'line' ? 'line' : 'bar',
      wide: slot.size === 'wide',
      series: slot.kpi.buildSeries ? slot.kpi.buildSeries() : []
    }));

    const scorecardHtml = scorecards.map((slot) => `
      <div class="tile">
        <div class="tile-label">${escapeHtml(slot.kpi.label)}</div>
        <div class="tile-value">${escapeHtml(formatDisplay(slot.kpi))}</div>
        <div class="tile-note">${escapeHtml(slot.kpi.explain || '')}</div>
      </div>`).join('');

    const chartHtml = chartData.map((c) => `
      <div class="chart-card ${c.wide ? 'wide' : ''}">
        <h3>${escapeHtml(c.title)}</h3>
        <canvas id="${c.id}"></canvas>
      </div>`).join('');

    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)} — Dashboard</title>
<script src="https://cdnjs.cloudflare.com/ajax/libs/Chart.js/4.4.4/chart.umd.min.js"></script>
<style>
  :root{ --brand:#4f46e5; --ink-900:#0f172a; --ink-500:#64748b; --ink-200:#e2e8f0; }
  *{box-sizing:border-box}
  body{margin:0;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;background:#f8fafc;color:var(--ink-900)}
  header{padding:28px 32px;background:#fff;border-bottom:1px solid var(--ink-200)}
  header h1{margin:0;font-size:1.4rem}
  header p{margin:6px 0 0;color:var(--ink-500);font-size:.85rem}
  main{max-width:1100px;margin:0 auto;padding:28px 20px 60px}
  .tiles{display:grid;grid-template-columns:repeat(auto-fit,minmax(200px,1fr));gap:16px;margin-bottom:24px}
  .tile{background:#fff;border:1px solid var(--ink-200);border-radius:14px;padding:18px}
  .tile-label{font-size:.72rem;font-weight:700;text-transform:uppercase;letter-spacing:.05em;color:var(--ink-500)}
  .tile-value{font-size:1.9rem;font-weight:800;color:#312e81;margin:6px 0}
  .tile-note{font-size:.75rem;color:var(--ink-500)}
  .charts{display:grid;grid-template-columns:1fr 1fr;gap:16px}
  .chart-card{background:#fff;border:1px solid var(--ink-200);border-radius:14px;padding:18px;min-width:0}
  .chart-card.wide{grid-column:1/-1}
  .chart-card h3{margin:0 0 12px;font-size:.95rem}
  @media(max-width:720px){.charts{grid-template-columns:1fr}}
  footer{text-align:center;color:var(--ink-500);font-size:.75rem;padding:20px}
</style>
</head>
<body>
<header>
  <h1>${escapeHtml(title)}</h1>
  <p>Generated by the DocBrisk KPI add-in — data is baked into this file, not live-connected to the workbook.</p>
</header>
<main>
  <div class="tiles">${scorecardHtml}</div>
  <div class="charts">${chartHtml}</div>
</main>
<footer>Built with DocBrisk · docbrisk.com</footer>
<script>
const CHART_DATA = ${JSON.stringify(chartData).replace(/</g, '\\u003c')};
CHART_DATA.forEach(function (c) {
  const ctx = document.getElementById(c.id).getContext('2d');
  new Chart(ctx, {
    type: c.type,
    data: {
      labels: c.series.map(function (p) { return p.label; }),
      datasets: [{
        data: c.series.map(function (p) { return p.value; }),
        backgroundColor: '#6366f1',
        borderColor: '#4f46e5',
        tension: 0.3
      }]
    },
    options: {
      responsive: true,
      plugins: { legend: { display: false } },
      scales: { y: { beginAtZero: true } }
    }
  });
});
</script>
</body>
</html>`;
  }

  return { buildHtml };
})();

if (typeof module !== 'undefined' && module.exports) module.exports = DashboardExport;
